import hmac
import hashlib
import pytest
from httpx import AsyncClient
from app.config import settings


@pytest.mark.asyncio
async def test_get_subscription_plans(client: AsyncClient):
    """Verify all 3 configurable SaaS plans (START, BUSINESS, PRO) are returned with Armenian AMD pricing."""
    res = await client.get("/api/v1/subscriptions/plans")
    assert res.status_code == 200
    plans = res.json()
    assert len(plans) == 3
    plan_ids = [p["id"] for p in plans]
    assert "START" in plan_ids
    assert "BUSINESS" in plan_ids
    assert "PRO" in plan_ids

    biz_plan = next(p for p in plans if p["id"] == "BUSINESS")
    assert biz_plan["monthly_price_amd"] == 24900
    assert biz_plan["limits"]["max_products"] == 2500
    assert biz_plan["limits"]["has_advanced_reports"] is True


@pytest.mark.asyncio
async def test_get_current_subscription_and_quotas(client: AsyncClient, auth_headers: dict):
    """Verify subscription status, expiration countdown, and quota calculation."""
    res = await client.get("/api/v1/subscriptions/current", headers=auth_headers)
    assert res.status_code == 200
    data = res.json()
    assert "subscription" in data
    assert "quotas" in data
